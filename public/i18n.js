  let locale;
  try { locale = localStorage.getItem(STORAGE_KEY); } catch { /* Storage is optional. */ }
  if (locale !== 'id' && locale !== 'en') locale = 'id';
  document.documentElement.lang = locale;

  function t(key, variables = {}) {
    const template = messages[locale][key] ?? messages.id[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (match, name) => variables[name] ?? match);
  }

  function apiUrl(path) {
    const separator = path.includes('?') ? '&' : '?';
    return `${path}${separator}lang=${encodeURIComponent(locale)}`;
  }

  function apiFetch(path, options) {
    return fetch(apiUrl(path), options);
  }

  function apply(root = document) {
    root.querySelectorAll('[data-i18n]').forEach(element => { element.textContent = t(element.dataset.i18n); });
    root.querySelectorAll('[data-i18n-placeholder]').forEach(element => { element.placeholder = t(element.dataset.i18nPlaceholder); });
    root.querySelectorAll('[data-i18n-aria-label]').forEach(element => { element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel)); });
    root.querySelectorAll('[data-i18n-title]').forEach(element => { element.title = t(element.dataset.i18nTitle); });
    root.querySelectorAll('[data-i18n-alt]').forEach(element => { element.alt = t(element.dataset.i18nAlt); });
    root.querySelectorAll('[data-language-switch]').forEach(select => { select.value = locale; });
  }

  function setLocale(next) {
    if (!Object.hasOwn(messages, next) || next === locale) return;
    let persisted = false;
    try { localStorage.setItem(STORAGE_KEY, next); persisted = true; } catch { /* Current page can still switch. */ }
    locale = next;
    document.documentElement.lang = locale;
    apply();
    window.dispatchEvent(new CustomEvent('coc-language-changed', { detail: { locale } }));
    // Rendered API content is rebuilt using the selected locale on navigation/reload.
    if (persisted) window.location.reload();
  }

  window.CocI18n = {
    t, apply, setLocale, apiUrl, apiFetch,
    hasTranslation: (key, language) => Object.hasOwn(messages[language] || {}, key),
    get locale() { return locale; },
    get formatLocale() { return locale === 'id' ? 'id-ID' : 'en-US'; },
    number: (value, options) => new Intl.NumberFormat(locale === 'id' ? 'id-ID' : 'en-US', options).format(value),
    dateTime: (value, options) => new Intl.DateTimeFormat(locale === 'id' ? 'id-ID' : 'en-US', options).format(value)
  };

  document.addEventListener('DOMContentLoaded', () => {
    apply();
    document.querySelectorAll('[data-language-switch]').forEach(select => {
      select.addEventListener('change', event => setLocale(event.target.value));
    });
  });
